import 'row_parsing.dart';

class Patient {
  final String id;
  final String name;
  final int age;
  final String gender;
  final String wardId;
  final String bedNumber;
  final String diagnosis;
  final String? bloodGroup;
  final DateTime admittedAt;
  final bool isActive;
  final String hlsStreamUrl;

  const Patient({
    required this.id,
    required this.name,
    required this.age,
    required this.gender,
    required this.wardId,
    required this.bedNumber,
    required this.diagnosis,
    this.bloodGroup,
    required this.admittedAt,
    this.isActive = true,
    this.hlsStreamUrl = '',
  });

  /// Builds a patient from a `patients` row.
  factory Patient.fromRow(DbRow row) {
    return Patient(
      id: row['id'] as String? ?? '',
      name: row['name'] as String? ?? '',
      age: (row['age'] as num?)?.toInt() ?? 0,
      gender: row['gender'] as String? ?? '',
      wardId: row['ward_id'] as String? ?? '',
      bedNumber: row['bed_number'] as String? ?? '',
      diagnosis: row['diagnosis'] as String? ?? '',
      bloodGroup: row['blood_group'] as String?,
      admittedAt: parseTimestamp(row['admitted_at']),
      isActive: row['is_active'] as bool? ?? true,
      hlsStreamUrl: row['hls_stream_url'] as String? ?? '',
    );
  }

  /// Columns written on insert/update (`id` is generated by Postgres).
  DbRow toRow() {
    return {
      'name': name,
      'age': age,
      'gender': gender,
      'ward_id': wardId,
      'bed_number': bedNumber,
      'diagnosis': diagnosis,
      'blood_group': bloodGroup,
      'admitted_at': toTimestamp(admittedAt),
      'is_active': isActive,
    };
  }

  String get initials {
    final trimmed = name.trim();
    if (trimmed.isEmpty) return '';
    final parts = trimmed.split(RegExp(r'\s+'));
    final first = parts.first.isNotEmpty ? parts.first[0] : '';
    final second = parts.length > 1 && parts[1].isNotEmpty
        ? parts[1][0]
        : (parts.first.length > 1 ? parts.first[1] : '');
    return (first + second).toUpperCase();
  }
}
